export function useT() {
  const language = useContext(LanguageContext);
  return (key: string) => translate(key, language);
}
export function money(value?: { amount: number; currency: string }) {
  const locale = typeof document !== 'undefined' ? document.documentElement.lang : 'ru-KZ';
  return value
    ? `${new Intl.NumberFormat(locale, { maximumFractionDigits: 2 }).format(value.amount / 100)} ${value.currency}`
    : '—';
}
export function date(value: string | undefined, zone?: string) {
  if (!value) return '—';
  const locale = typeof document !== 'undefined' ? document.documentElement.lang : 'ru-KZ';
  return new Intl.DateTimeFormat(locale, {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone: zone,
  }).format(new Date(value));
}
export function errorKey(code: string, status: number) {
  if (code === 'network_error') return 'Cannot reach the server. Check your connection.';
  if (code === 'invalid_credentials') return 'Wrong email or password.';
  if (code === 'email_taken') return 'This email is already registered.';
  if (code === 'email_not_verified') return 'Verify your email first.';
  if (code === 'token_invalid' || code === 'token_expired')
    return 'This link is invalid or expired.';
  if (code.startsWith('promo_code')) return 'This promo code cannot be used.';
  if (code === 'checkout_expired' || code === 'checkout_abandoned')
    return 'Your hold expired. Start again.';
  if (status === 402) return 'Payment failed. Try another simulated result.';
  if (status === 401) return 'Your session ended. Please sign in again.';
  if (status === 403) return 'You do not have permission for this action.';
  if (status === 422) return 'Check the form fields.';
  if (['sold_out', 'seat_taken', 'seat_unavailable'].includes(code))
    return 'These tickets are no longer available.';
  return 'Something went wrong. Try again.';
}
